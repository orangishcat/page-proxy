// There's probably a better way to do this, but this works for now
// TODO: pass source files to Monaco directly somehow

import path from "node:path";
import { fileURLToPath } from "node:url";
import { mkdir, writeFile } from "node:fs/promises";
import ts from "typescript";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const extensionDir = path.resolve(scriptDir, "..");
const outputFile = path.join(extensionDir, "src/types/pp-monaco-extra-lib.txt");
const outDir = path.join(extensionDir, ".tmp/pp-monaco-types");
const sourceFiles = [
  path.join(extensionDir, "src/lib/pp/pp-query.ts"),
  path.join(extensionDir, "src/lib/pp/pp-style.ts"),
  path.join(extensionDir, "src/lib/pp/pp-event.ts"),
  path.join(extensionDir, "src/lib/pp/pp-api.ts"),
];

const sourceModuleSpecs = [
  { sourceFile: "pp-query.d.ts", moduleName: "@/lib/pp/pp-query" },
  { sourceFile: "pp-style.d.ts", moduleName: "@/lib/pp/pp-style" },
  { sourceFile: "pp-event.d.ts", moduleName: "@/lib/pp/pp-event" },
  { sourceFile: "pp-api.d.ts", moduleName: "@/lib/pp/pp-api" },
];

const compilerOptions = {
  target: ts.ScriptTarget.ES2022,
  module: ts.ModuleKind.ESNext,
  moduleResolution: ts.ModuleResolutionKind.Bundler,
  declaration: true,
  emitDeclarationOnly: true,
  noEmitOnError: true,
  allowImportingTsExtensions: true,
  strict: true,
  skipLibCheck: true,
  rootDir: path.join(extensionDir, "src/lib"),
  outDir,
};

const emittedDeclarations = new Map();
const host = ts.createCompilerHost(compilerOptions);
host.writeFile = (fileName, content) => {
  if (!fileName.endsWith(".d.ts")) {
    return;
  }
  emittedDeclarations.set(path.basename(fileName), content);
};

const program = ts.createProgram(sourceFiles, compilerOptions, host);
const emitResult = program.emit();
const diagnostics = ts.getPreEmitDiagnostics(program).concat(emitResult.diagnostics);
if (diagnostics.length > 0) {
  const message = ts.formatDiagnosticsWithColorAndContext(diagnostics, {
    getCurrentDirectory: () => extensionDir,
    getCanonicalFileName: (value) => value,
    getNewLine: () => "\n",
  });
  throw new Error(message);
}

const rewriteImports = (source) =>
  source
    .replace(/import\("\.\/([^"]+)"\)/g, 'import("@/lib/pp/$1")')
    .replace(/import\("\.\.\/([^"]+)"\)/g, 'import("@/lib/$1")')
    .replace(/from "\.\/([^"]+)"/g, 'from "@/lib/pp/$1"')
    .replace(/from "\.\.\/([^"]+)"/g, 'from "@/lib/$1"');

const wrapModuleDeclaration = (moduleName, source) => {
  const trimmedSource = rewriteImports(source.trim());
  const indentedSource = trimmedSource
    .split("\n")
    .map((line) => (line.length > 0 ? `  ${line}` : line))
    .join("\n");
  return `declare module "${moduleName}" {\n${indentedSource}\n}`;
};

const output = [
  "// Generated by extension/scripts/generate-pp-monaco-extra-lib.mjs",
  "// Do not edit manually.",
  "",
  ...sourceModuleSpecs.map(({ sourceFile, moduleName }) => {
    const declaration = emittedDeclarations.get(sourceFile);
    if (!declaration) {
      throw new Error(`Missing emitted declaration file: ${sourceFile}`);
    }
    return wrapModuleDeclaration(moduleName, declaration);
  }),
  "",
].join("\n");

await mkdir(path.dirname(outputFile), { recursive: true });
await writeFile(outputFile, output, "utf8");
